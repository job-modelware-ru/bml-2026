import numpy as np

# Обучающая выборка (площадь x, цена y)
x = np.array([3, 4, 5])
y = np.array([10, 13, 17])

# Инициализация гиперпараметров
w = 2.0
alpha = 0.02
epochs = 2

# Цикл обучения
for i in range(epochs):
    # 1. Прямой проход (вычисление прогнозов)
    y_pred = w * x

    # 2. Вычисление вектора ошибок
    error = y_pred - y

    # 3. Вычисление градиента (векторизованное умножение и сумма)
    grad = (2 / len(x)) * np.sum(error * x)

    # 4. Шаг градиентного спуска
    w = w - alpha * grad

    print(f"Итерация {i + 1}: Градиент = {grad:.3f}, Новый вес = {w:.3f}")
